-- Login accounts, one per employee. Passwords are BCrypt hashes; the app creates
-- accounts for any employee that has none on startup (see UserAccountSeeder).
CREATE TABLE IF NOT EXISTS app_user (
    userid         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employeeid     INTEGER      NOT NULL UNIQUE REFERENCES employee (employeeid) ON DELETE CASCADE,
    username       VARCHAR(100) NOT NULL UNIQUE,
    passwordhash   VARCHAR(100) NOT NULL,
    role           VARCHAR(20)  NOT NULL DEFAULT 'EMPLOYEE'
                   CHECK (role IN ('ADMIN', 'HR', 'MANAGER', 'EMPLOYEE')),
    enabled        BOOLEAN      NOT NULL DEFAULT TRUE,
    failedattempts INTEGER      NOT NULL DEFAULT 0,
    lockeduntil    TIMESTAMP,
    tokenversion   INTEGER      NOT NULL DEFAULT 0,
    lastloginat    TIMESTAMP,
    createdat      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Records which one-off mock data sets (data.sql) have already been inserted.
CREATE TABLE IF NOT EXISTS mock_data_seed (
    name      VARCHAR(50) PRIMARY KEY,
    appliedat TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------------------
-- Documents, Tasks, Library and Help & support pages.
-- ---------------------------------------------------------------------------------

-- Company-wide documents have no owner; personal ones (offer letter, tax forms) do.
CREATE TABLE IF NOT EXISTS document (
    documentid  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(150) NOT NULL,
    category    VARCHAR(50)  NOT NULL,
    description VARCHAR(300),
    content     TEXT         NOT NULL,
    ownerid     INTEGER REFERENCES employee (employeeid) ON DELETE CASCADE,
    uploadedby  VARCHAR(120) NOT NULL,
    updatedat   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS task (
    taskid      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(150) NOT NULL,
    description TEXT,
    assigneeid  INTEGER      NOT NULL REFERENCES employee (employeeid) ON DELETE CASCADE,
    createdbyid INTEGER      REFERENCES employee (employeeid) ON DELETE SET NULL,
    priority    VARCHAR(10)  NOT NULL DEFAULT 'MEDIUM' CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    status      VARCHAR(15)  NOT NULL DEFAULT 'TODO' CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE')),
    duedate     DATE,
    createdat   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completedat TIMESTAMP
);

CREATE TABLE IF NOT EXISTS library_item (
    itemid      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    author      VARCHAR(150),
    category    VARCHAR(50)  NOT NULL,
    format      VARCHAR(10)  NOT NULL CHECK (format IN ('BOOK', 'EBOOK', 'VIDEO', 'COURSE')),
    description TEXT,
    totalcopies INTEGER      NOT NULL DEFAULT 1 CHECK (totalcopies >= 0)
);

-- A loan is active while returnedon is NULL.
CREATE TABLE IF NOT EXISTS library_loan (
    loanid     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    itemid     INTEGER NOT NULL REFERENCES library_item (itemid) ON DELETE CASCADE,
    employeeid INTEGER NOT NULL REFERENCES employee (employeeid) ON DELETE CASCADE,
    borrowedon DATE    NOT NULL DEFAULT CURRENT_DATE,
    dueon      DATE    NOT NULL,
    returnedon DATE
);

CREATE TABLE IF NOT EXISTS faq (
    faqid     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category  VARCHAR(50)  NOT NULL,
    question  VARCHAR(300) NOT NULL,
    answer    TEXT         NOT NULL,
    sortorder INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS support_ticket (
    ticketid    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employeeid  INTEGER      NOT NULL REFERENCES employee (employeeid) ON DELETE CASCADE,
    category    VARCHAR(20)  NOT NULL CHECK (category IN ('IT', 'HR', 'PAYROLL', 'FACILITIES', 'OTHER')),
    subject     VARCHAR(150) NOT NULL,
    description TEXT         NOT NULL,
    priority    VARCHAR(10)  NOT NULL DEFAULT 'MEDIUM' CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    status      VARCHAR(15)  NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
    resolution  TEXT,
    createdat   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedat   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_document_owner ON document (ownerid);
CREATE INDEX IF NOT EXISTS idx_task_assignee ON task (assigneeid);
CREATE INDEX IF NOT EXISTS idx_task_creator ON task (createdbyid);
CREATE INDEX IF NOT EXISTS idx_loan_employee ON library_loan (employeeid);
CREATE INDEX IF NOT EXISTS idx_loan_item_active ON library_loan (itemid) WHERE returnedon IS NULL;
CREATE INDEX IF NOT EXISTS idx_ticket_employee ON support_ticket (employeeid);
