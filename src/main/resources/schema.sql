-- Runs on every application start. Every statement is safe to repeat.

-- The original tables have integer primary keys with no default, so new rows need
-- an ID source. These sequences are re-aligned to MAX(id) + 1 on each start.
CREATE SEQUENCE IF NOT EXISTS employee_seq;
CREATE SEQUENCE IF NOT EXISTS address_seq;
CREATE SEQUENCE IF NOT EXISTS leaverequest_seq;

SELECT setval('employee_seq', (SELECT COALESCE(MAX(employeeid), 0) + 1 FROM employee), false);
SELECT setval('address_seq', (SELECT COALESCE(MAX(addressid), 0) + 1 FROM address), false);
SELECT setval('leaverequest_seq', (SELECT COALESCE(MAX(leaveid), 0) + 1 FROM leaverequest), false);

-- New tables for the News & events page.
CREATE TABLE IF NOT EXISTS announcement (
    announcementid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(150) NOT NULL,
    summary        TEXT         NOT NULL,
    author         VARCHAR(120) NOT NULL,
    postedat       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS company_event (
    eventid     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(150) NOT NULL,
    description TEXT,
    eventdate   DATE         NOT NULL,
    location    VARCHAR(100)
);

